#!/usr/bin/env python3
"""Generate driver/dmtd_constants.py from gen/design.py.

The driver runs on the PYNQ, where the schematic generator is not installed,
so it cannot import gen/design.py at run time -- but it must not carry its own
copy of the numbers either.  So the numbers are generated, exactly the way the
XDC is, and the generated file is checked in.  Board, gateware and driver then
cannot disagree about which GPSDO is on which channel or what a helper cycle
is worth in picoseconds.

    python3 gateware/gen_constants.py gateware/driver/dmtd_constants.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from gen import design  # noqa: E402


def main(out=sys.stdout):
    w = out.write
    w('"""Constants for the GPSDO DDMTD overlay.\n\n'
      'GENERATED by gateware/gen_constants.py from gen/design.py.\n'
      'Do not edit: edit gen/design.py and re-run the build.\n"""\n\n')

    w("# ---- the DDMTD numbers ----------------------------------------------\n")
    w("F_SIGNAL = %r        # Hz, the references under test\n" % design.F_SIGNAL)
    w("F_HELPER = %r        # Hz, Si5351 CLK0\n" % design.F_HELPER)
    w("F_BEAT   = %r        # Hz, F_HELPER - F_SIGNAL\n" % design.F_BEAT)
    w("N_GAIN   = %r        # heterodyne gain, F_SIGNAL / F_BEAT\n" % design.N_GAIN)
    w("T_RES_PS = %r        # ps of input phase per helper cycle of beat displacement\n"
      % design.T_RES_PS)
    cyc = design.F_HELPER / design.F_BEAT
    w("\n# Helper cycles in one beat period: F_HELPER/F_BEAT, which is N_GAIN+1\n"
      "# and NOT N_GAIN -- N_GAIN is the time-stretch gain, a different\n"
      "# quantity that happens to sit right next to it.  A displacement of this\n"
      "# many helper cycles is one whole 10 MHz cycle of input phase, 100 ns,\n"
      "# which is where the measurement wraps.  It is not an integer, so real\n"
      "# beat periods alternate between %d and %d helper cycles.\n"
      % (int(cyc), int(cyc) + 1))
    w("HELPER_CYCLES_PER_BEAT = F_HELPER / F_BEAT\n")
    w("WRAP_PS = 1e12 / F_SIGNAL      # %.1f ps, one input cycle\n\n"
      % (1e12 / design.F_SIGNAL))

    beats = [u for u in design.UNITS]
    pps = [u for u in design.UNITS if u[2]]
    w("# ---- channel map ----------------------------------------------------\n")
    w("# Register offset for channel n is 0x200 + 16*n; beats are slots 0..%d\n"
      "# and pps returns are slots %d..%d.\n"
      % (len(beats) - 1, 16, 16 + len(pps) - 1))
    w("N_BEAT = %d\n" % len(beats))
    w("N_PPS  = %d\n" % len(pps))
    w("PPS0   = 16\n\n")

    w("# beat channel -> the GPSDO on it\n")
    w("UNIT_NAMES = [\n")
    for u in beats:
        w("    %r,\n" % u[3])
    w("]\n\n")

    w("# beat channel -> pps slot, or None where that unit has no 1 pps output\n")
    w("PPS_SLOT = [\n")
    n = 0
    for u in beats:
        if u[2]:
            w("    %d,%s# %s -> %s\n" % (16 + n, " " * 6, u[1], u[2]))
            n += 1
        else:
            w("    None,   # %s has no pps\n" % u[1])
    w("]\n\n")

    null = [i for i, u in enumerate(beats) if "NULL" in u[3].upper()]
    w("# The null channel is the helper compared against itself through an\n"
      "# identical signal path.  Subtracting it removes everything common to\n"
      "# the board -- helper phase noise, the Si5351's own jitter, supply\n"
      "# pushing -- and leaves the difference between the GPSDOs, which is the\n"
      "# thing being measured.  It is the noise floor of the instrument.\n")
    w("NULL_CHANNEL = %s\n\n" % (null[0] if null else None))

    w("# ---- register map ---------------------------------------------------\n")
    for name, off in (("REG_ID", 0x000), ("REG_VERSION", 0x004),
                      ("REG_CONTROL", 0x008), ("REG_HELPER", 0x00C),
                      ("REG_LIVE_LO", 0x010), ("REG_LIVE_HI", 0x014),
                      ("REG_ALIVE", 0x018),
                      ("REG_LIVE_PS_LO", 0x01C), ("REG_LIVE_PS_HI", 0x020),
                      ("REG_CHAN0", 0x200), ("REG_PSCHAN0", 0x400)):
        w("%-14s = 0x%03X\n" % (name, off))
    w("# REG_LIVE_PS_*, REG_PSCHAN0: gateware 1.1 (round 28) -- the PS-domain\n"
      "# 10 ns timestamps of every pps and the (helper, PS) counter pair.\n")
    w("GATEWARE_MIN_MINOR_FOR_PS = 1\n")
    w("CHAN_STRIDE  = 0x010\n")
    w("OFF_TS_LO    = 0x000\n")
    w("OFF_TS_HI    = 0x004\n")
    w("OFF_COUNT    = 0x008\n\n")
    w("MAGIC_ID     = 0x444D5444      # 'DMTD'\n")
    w("BASE_ADDR    = 0x43C00000      # where the block design puts it\n")
    return 0


if __name__ == "__main__":
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w") as f:
            main(f)
        print("wrote %s" % sys.argv[1])
    else:
        main()
