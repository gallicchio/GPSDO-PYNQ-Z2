#!/usr/bin/env python3
"""Generate the pin constraints from gen/design.py.

The board and the gateware must agree about which FPGA ball carries which
signal, and the only way to guarantee that is to derive both from one file.
design.py already holds the header map -- the same table that places the
socket and names the nets -- so the XDC is generated from it rather than
typed again.  If a signal ever moves, it moves in both places or in neither.

    python3 gateware/gen_xdc.py > gateware/xdc/pins.xdc
"""
import os, sys, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "gen"))
import design as D                                       # noqa: E402

IOSTD = "LVCMOS33"          # bank 13 and bank 34 both run at 3.3 V on a PYNQ-Z2


def main(out=sys.stdout):
    rows = []
    for pin in range(1, 41):
        if pin not in D.HEADER:
            continue
        sig, ball, io, note = (list(D.HEADER[pin]) + [None] * 4)[:4]
        if sig == "GND" or sig.startswith("+"):
            continue
        rows.append((pin, sig, ball, io))

    beats = sorted((s, b, p) for p, s, b, _ in rows if s.startswith("BEAT_"))
    ppss = sorted((s, b, p) for p, s, b, _ in rows if s.startswith("PPS_"))
    other = [(s, b, p) for p, s, b, _ in rows
             if not s.startswith(("BEAT_", "PPS_"))]

    w = out.write
    w("# Pin constraints for the GPSDO DDMTD front end on a PYNQ-Z2.\n"
      "#\n"
      "# GENERATED by gateware/gen_xdc.py from gen/design.py -- do not edit.\n"
      "# %s\n#\n"
      "# Every ball here was cross-checked in round 22 against the TUL\n"
      "# schematic R12 sheet 4 and the PYNQ-Z2 Reference Manual v1.0.  Note\n"
      "# that eight of these balls are SHARED WITH PMOD A, so Pmod A cannot be\n"
      "# used while this board is fitted.\n\n"
      % datetime.date.today().isoformat())

    w("# ---- the helper clock -------------------------------------------\n")
    w("#\n"
      "# Header pin 18, the only clock-capable pin on the Raspberry Pi header\n"
      "# on BOTH the PYNQ-Z2 and the Icepi Zero.  gen/design.py asserts that\n"
      "# nothing may reassign it.\n"
      "#\n"
      "# The PYNQ puts a 200 ohm series resistor in every header GPIO, which\n"
      "# with the FPGA's input capacitance gives this clock a ~4.4 ns edge at\n"
      "# the die.  That is slow for a clock input; if bring-up shows double\n"
      "# clocking, that resistor is the reason.\n")
    for s, b, p in other:
        if s == "HELPER_CLK":
            w('set_property -dict {PACKAGE_PIN %s IOSTANDARD %s} '
              '[get_ports {helper_clk}]  ;# header pin %d\n' % (b, IOSTD, p))
            w('create_clock -period %.3f -name helper_clk '
              '[get_ports {helper_clk}]  ;# %.7f MHz\n\n'
              % (1e9 / D.F_HELPER, D.F_HELPER / 1e6))

    w("# ---- the thirteen beats, ~%.0f Hz ---------------------------------\n"
      % D.F_BEAT)
    for i, (s, b, p) in enumerate(beats):
        w('set_property -dict {PACKAGE_PIN %-4s IOSTANDARD %s} '
          '[get_ports {beat[%d]}]   ;# %-8s header pin %d\n'
          % (b, IOSTD, int(s.split("_")[1]), s, p))

    w("\n# ---- the twelve pps returns, 1 Hz ---------------------------------\n"
      "# There is no PPS_12: unit 13 is the null channel and has no pps.\n")
    for s, b, p in ppss:
        w('set_property -dict {PACKAGE_PIN %-4s IOSTANDARD %s} '
          '[get_ports {pps[%d]}]    ;# %-8s header pin %d\n'
          % (b, IOSTD, int(s.split("_")[1]), s, p))

    w("\n# ---- I2C to the Si5351, the thermometers, the DAC and the bridge --\n"
      "# 2k2 pull-ups are already fitted on the PYNQ (R305-R308); the front-end\n"
      "# board deliberately fits none.\n")
    for s, b, p in other:
        if s.startswith("I2C_"):
            nm = "iic_" + s.split("_")[1].lower() + "_io"
            w('set_property -dict {PACKAGE_PIN %-4s IOSTANDARD %s PULLUP true} '
              '[get_ports {%s}]  ;# %-8s header pin %d\n'
              % (b, IOSTD, nm, s, p))

    w("\n# ---- timing ------------------------------------------------------\n"
      "# Beats and pps are asynchronous to the PS clock and are taken into the\n"
      "# helper domain through two-flop synchronisers, so they are declared\n"
      "# false paths.  The measurement does NOT depend on their setup/hold\n"
      "# against the helper: it depends on the counter value latched when the\n"
      "# synchroniser sees the edge.\n")
    w("set_false_path -from [get_ports {beat[*]}]\n")
    w("set_false_path -from [get_ports {pps[*]}]\n\n")
    w("# The helper comes from the Si5351 on the front-end board and is not\n"
      "# phase-related to anything inside the FPGA.  Without this Vivado tries\n"
      "# to time every timestamp bit crossing out of the helper domain and\n"
      "# reports thousands of failing endpoints that mean nothing -- the\n"
      "# crossing is handled by the toggle-synchroniser in dmtd_capture, not by\n"
      "# timing closure.\n"
      "#\n"
      "# The second group is 'every other clock' rather than clk_fpga_0 by\n"
      "# name, so this is still correct for the bring-up variant, which runs\n"
      "# the AXI fabric from the board's own 125 MHz oscillator instead.\n")
    w("#\n"
      "# ONE group, deliberately.  set_clock_groups with a single -group means\n"
      "# 'this group is asynchronous to every other clock in the design', and\n"
      "# that is resolved at analysis time rather than when this file is read.\n"
      "# Naming the other clocks -- or computing them from all_clocks -- makes\n"
      "# the constraint depend on XDC ordering, and a clock created later (the\n"
      "# PS7's clk_fpga_0, an MMCM output) then silently falls outside the\n"
      "# group.  The symptom is thousands of failing CDC endpoints in a timing\n"
      "# report that points at the design instead of at the constraint.\n")
    w("if {![llength [get_clocks -quiet helper_clk]]} {\n"
      "    error \"pins.xdc: helper_clk is not defined -- the create_clock above\\\n"
      " did not match a port, so nothing below constrains anything.\"\n"
      "}\n"
      "set_clock_groups -asynchronous \\\n"
      "    -group [get_clocks -include_generated_clocks helper_clk]\n")
    return 0


if __name__ == "__main__":
    if len(sys.argv) > 1:
        with open(sys.argv[1], "w") as f:
            main(f)
        print("wrote %s" % sys.argv[1])
    else:
        main()
